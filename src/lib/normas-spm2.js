// Convierte las filas en mapas raw -> { t, pct } por escala
function construirMapa(filas) {
  const escalas = ["VIS", "HEA", "TOU", "TS", "BOD", "BAL", "ST", "PLN", "SOC"];
  const mapa = Object.fromEntries(escalas.map((e) => [e, {}]));
  for (const fila of filas) {
    const [pct, t, ...valores] = fila;
    escalas.forEach((escala, i) => {
      const celda = valores[i];
      if (celda == null) return;
      let min, max;
      if (typeof celda === "string") {
        const [a, b] = celda.split("-").map(Number);
        min = a;
        max = b;
      } else {
        min = max = celda;
      }
      for (let raw = min; raw <= max; raw++) {
        mapa[escala][raw] = { t, pct };
      }
    });
  }
  return mapa;
}

const MAPAS = Object.fromEntries(
  Object.entries(F).map(([clave, filas]) => [clave, construirMapa(filas)])
);

export const TABLAS_NORMAS = MAPAS;

